# intro TITLE: the opening frame, in place of the library's banner, whose text promises values
# remembered in a .env this wizard doesn't keep.
intro() {
  _clear
  printf '\n%s%s  %s%s\n' "$BOLD" "$BLUE" "$1" "$RESET"
  printf '%s  %s stages. This wizard runs the gh steps and reads each result back; you confirm\n' "$DIM" "$TOTAL_STAGES"
  printf '  each change first. Stop with Ctrl-C any time; re-running is safe.%s\n\n' "$RESET"
  pause "Ready to start?"
