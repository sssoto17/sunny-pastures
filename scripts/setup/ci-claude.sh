step "(a separate browser profile keeps your personal account out of it)."
step "Open a NEW terminal window, not this one, and run: claude setup-token"
step "Approve in the browser. Check the organisation shown is your employer's."
step "Copy the token it prints. Leave that window open for the next stage."
warn "Never paste that window, or the token, into a Claude session or a chat."
pause "Press Enter once the token is copied"

stage "Store the token"
say "Paste it below. Input is hidden; it goes straight to gh secret set."
ask_secret _CI_CLAUDE_TOKEN "Token:" || die 2 "input ended"
case $_CI_CLAUDE_TOKEN in
  "") die 2 "nothing pasted" ;;
  sk-ant-api*) _CI_CLAUDE_TOKEN=""; die 2 "that is an API key, not a setup-token; nothing was stored" ;;
  sk-ant-oat*) ;;
  *) warn "it doesn't start like a setup-token (sk-ant-oat…); storing it anyway" ;;
esac
for env in factory review; do
  printf '%s' "$_CI_CLAUDE_TOKEN" |
    gh secret set CLAUDE_CODE_OAUTH_TOKEN --env "$env" --repo "$REPO" >/dev/null ||
    { _CI_CLAUDE_TOKEN=""; die 1 "gh secret set CLAUDE_CODE_OAUTH_TOKEN --env $env failed"; }
  WRITTEN_SECRET+=("CLAUDE_CODE_OAUTH_TOKEN ($env)")
  printf '  %s✓ set%s secret CLAUDE_CODE_OAUTH_TOKEN in environment %s\n' "$GREEN" "$RESET" "$env"
done
_CI_CLAUDE_TOKEN=""
step "Now clear the other window (clear && printf '\\033[3J'), then close it."
step "Clear your clipboard too (copy any harmless text)."
pause "Press Enter once that window is closed"

stage "Allow the pinned action"
mode=$(gh api "repos/$REPO/actions/permissions" --jq .allowed_actions) ||
  die 1 "reading the Actions permissions failed"
[[ $mode == selected ]] ||
  die 2 "allowed actions is \"$mode\", not \"selected\": do ADR-0002 checklist step 8 first"
sel=repos/$REPO/actions/permissions/selected-actions
owned=$(gh api "$sel" --jq .github_owned_allowed) || die 1 "reading the selected actions failed"
verified=$(gh api "$sel" --jq .verified_allowed) || die 1 "reading the selected actions failed"
# Read the list into a variable first: a failed read must stop here, not empty the list we write.
listed=$(gh api "$sel" --jq '.patterns_allowed // [] | .[]') || die 1 "reading the selected actions failed"
patterns=()
while IFS= read -r p; do [[ -z $p ]] || patterns+=("$p"); done <<<"$listed"
say "Allowed now: GitHub-owned $owned, verified creators $verified, patterns:"
for p in "${patterns[@]}"; do note "  $p"; done
fields=()
for p in "${patterns[@]}" "${ACTION_PATTERNS[@]}"; do
  [[ " ${fields[*]} " == *" patterns_allowed[]=$p "* ]] || fields+=("patterns_allowed[]=$p")
done
say "After this stage, the patterns will be:"
for f in "${fields[@]}"; do note "  ${f#patterns_allowed[]=}"; done
if confirm "Write this list? GitHub-owned and verified stay as they are"; then
  args=(-F "github_owned_allowed=$owned" -F "verified_allowed=$verified")
  for f in "${fields[@]}"; do args+=(-f "$f"); done
  gh api -X PUT "$sel" --silent "${args[@]}" ||
    die 1 "writing the selected actions failed"
  printf '  %s✓ allowed%s the pinned claude-code-action\n' "$GREEN" "$RESET"
else
  SKIPPED+=("Allowed actions: add ${ACTION_PATTERNS[*]}")
fi
pause

stage "Check what is set (names only)"
for env in factory review; do
  names=$(gh secret list --env "$env" --repo "$REPO" --json name --jq '.[].name') ||
    die 1 "gh secret list --env $env failed"
  say "Environment $env, secrets:"; note "  ${names//$'\n'/, }"
done
listed=$(gh api "$sel" --jq '.patterns_allowed // [] | .[]') || die 1 "reading the selected actions failed"
say "Allowed action patterns:"; note "  ${listed//$'\n'/, }"
say "Next: scripts/setup/ci-check.sh start 103."
pause

finish
}

