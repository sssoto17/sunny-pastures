run_wizard() {

TOTAL_STAGES=4

intro "#102: read the Project from Actions ($kind token)"

stage "Check gh and the environment"
command -v gh >/dev/null 2>&1 || die 2 "gh is not installed: https://cli.github.com"
gh auth status >/dev/null 2>&1 || die 2 "gh is signed out: run gh auth login, then re-run this"
gh api -X PUT "repos/$REPO/environments/sweep" --silent || die 1 "creating environment sweep failed"
printf '  %s✓ environment%s sweep\n' "$GREEN" "$RESET"
pause

stage "Create the token ($kind)"
if [[ $kind == classic ]]; then
  open_url "https://github.com/settings/tokens/new"
  step "Note: sunny-pastures #102 project read. Expiration: 7 days."
  step "Scopes: tick only read:project. Nothing else, not the project box above it."
  warn "Never tick repo: it reaches every private repo your account can, your employer's too."
else
  open_url "https://github.com/settings/personal-access-tokens/new?name=sunny-pastures+project+read&description=%23102+check&expires_in=7"
  step "Resource owner: sssoto17. Repository access: Only select repositories → sunny-pastures."
  step "Repository permissions: leave Metadata (read-only); add nothing that writes."
  step "Account permissions: Projects → Read-only, if the page offers it."
  note "GitHub's docs list user-owned Projects as a gap of fine-grained tokens, so this may fail."
  warn "No script can check this token's repository and permission limits: set them as above."
fi
step "Click Generate token and copy it. GitHub shows it once."
warn "Never paste the token, or that page, into a Claude session or a chat."
pause "Press Enter once it is copied"

stage "Store the token"
say "Paste it below. Input is hidden; it goes straight to gh secret set."
ask_secret _CI_PROJECT_TOKEN "Token:" || die 2 "input ended"
case $kind:$_CI_PROJECT_TOKEN in
  classic:ghp_*)
    scopes=$(GH_TOKEN=$_CI_PROJECT_TOKEN gh api -i user 2>/dev/null | tr -d '\r' |
      sed -n 's/^[Xx]-[Oo][Aa]uth-[Ss]copes: *//p') || true
    if [[ $scopes != read:project ]]; then
      _CI_PROJECT_TOKEN=""
      die 2 "the token's scopes are \"${scopes:-unknown}\", not only read:project; nothing stored. Delete it on GitHub"
    fi
    say "Scopes: read:project only." ;;
  fine-grained:github_pat_*) ;;
  *:) die 2 "nothing pasted" ;;
  *) _CI_PROJECT_TOKEN=""; die 2 "that isn't a $kind token (ghp_… or github_pat_…); nothing stored" ;;
esac
printf '%s' "$_CI_PROJECT_TOKEN" | gh secret set PROJECT_READ_TOKEN --env sweep --repo "$REPO" >/dev/null ||
  { _CI_PROJECT_TOKEN=""; die 1 "gh secret set PROJECT_READ_TOKEN --env sweep failed"; }
_CI_PROJECT_TOKEN=""
WRITTEN_SECRET+=("PROJECT_READ_TOKEN (sweep)")
printf '  %s✓ set%s secret PROJECT_READ_TOKEN in environment sweep\n' "$GREEN" "$RESET"
step "Clear your clipboard (copy any harmless text)."
pause

stage "Check what is set (names only)"
names=$(gh secret list --env sweep --repo "$REPO" --json name --jq '.[].name') ||
  die 1 "gh secret list --env sweep failed"
say "Environment sweep, secrets:"; note "  ${names//$'\n'/, }"
say "Next: scripts/setup/ci-check.sh start 102."
pause

finish
}

run_wizard "$@"; exit
