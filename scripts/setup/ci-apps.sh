# store_key ENV NAME: asks for the .pem path and sends the file to `gh secret set` on stdin. The
# key never passes through a shell variable, an argument or the terminal.
store_key() {
  local env=$1 name=$2 pem dir root
  root=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
  while :; do
    ask PEM_PATH "Path to the downloaded .pem file:" || die 2 "input ended"
    pem=${PEM_PATH/#\~/$HOME}
    if [[ ! -f $pem ]]; then warn "no file at $pem"; continue; fi
    if ! grep -q -e '-----BEGIN .*PRIVATE KEY-----' "$pem"; then
      warn "that file isn't a PEM private key"; continue
    fi
    break
  done
  dir=$(cd "$(dirname "$pem")" && pwd -P)
  [[ $dir/ == "$(cd "$root" && pwd -P)"/* ]] &&
    warn "the key is inside the repo; *.pem is gitignored, but move keys outside it next time"
  gh secret set "$name" --env "$env" --repo "$REPO" <"$pem" >/dev/null ||
    die 1 "gh secret set $name --env $env failed"
  WRITTEN_SECRET+=("$name ($env)")
  printf '  %s✓ set%s secret %s in environment %s\n' "$GREEN" "$RESET" "$name" "$env"
  if confirm "Delete $pem now? GitHub keeps only the public half; a new key is one click"; then
    rm -f -- "$pem" && say "deleted"
  else
    warn "delete it yourself once you're done: it is a live credential"
  fi
}

# app_stages SLUG PREFIX ENV PERMS DESCRIPTION: register, key, install. Three stages.
app_stages() {
  local slug=$1 prefix=$2 env=$3 perms=$4 what=$5
  stage "$slug: register the App"
  say "$what"
  open_url "https://github.com/settings/apps/new?name=$slug&url=https://github.com/$REPO&public=false&$perms"
  step "The form is prefilled. Check: Webhook \"Active\" is unticked."
  step "Repository permissions: only those listed below, plus Metadata: Read-only (mandatory)."
  note "  ${perms//&/, }  (write = Read and write)"
  step "Leave Administration and Workflows at No access. Where can it be installed: Only on this account."
  step "Click Create GitHub App. If the name is taken, pick another and note the slug from its URL."
  step "On the App's page (General), copy the Client ID. It is not the App ID."
  ask CLIENT_ID "Client ID:" || die 2 "input ended"
  [[ $CLIENT_ID =~ ^Iv[0-9A-Za-z._-]+$ ]] || warn "client IDs usually start with Iv; check it"
  gh variable set "${prefix}_APP_CLIENT_ID" --env "$env" --repo "$REPO" --body "$CLIENT_ID" >/dev/null ||
    die 1 "gh variable set ${prefix}_APP_CLIENT_ID --env $env failed"
  printf '  %s✓ set%s variable %s in environment %s\n' "$GREEN" "$RESET" "${prefix}_APP_CLIENT_ID" "$env"
  pause

  stage "$slug: private key"
  step "On the App's settings page: Private keys → Generate a private key"
  step "(on newer pages: Credentials → Key pairs → New key). The browser downloads a .pem file."
  warn "Save it outside the repo, and never open it or paste it into a session."
  store_key "$env" "${prefix}_APP_PRIVATE_KEY"
  pause

  stage "$slug: install it on this repo only"
  step "On the App's settings page: Install App → Install next to your account."
  step "Choose Only select repositories → $REPO → Install."
  warn "Not All repositories: your account reaches other private repos."
  pause "Press Enter once it is installed"
}

