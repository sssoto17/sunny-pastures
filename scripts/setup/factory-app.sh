ok() { printf '  %s✓%s %s\n' "$GREEN" "$RESET" "$1"; }

# env_policy: "<protected_branches> <custom_branch_policies>", or "missing".
env_policy() {
  gh api "$E" --jq '.deployment_branch_policy // {} | "\(.protected_branches) \(.custom_branch_policies)"' \
    2>/dev/null || echo missing
}

# check_env: `factory-app` may be used by main and nothing else, or the wizard stops.
check_env() {
  local policy have
  policy=$(env_policy)
  [[ $policy == "false true" ]] ||
    die 1 "$ENV_NAME isn't limited to Selected branches (policy: $policy): set Deployment branches and tags → Selected branches and tags in its settings, then re-run"
  have=$(gh api "$E/deployment-branch-policies" --jq '.branch_policies[] | "\(.type // "branch") \(.name)"') ||
    die 1 "reading the branch policies of $ENV_NAME failed"
  [[ $have == "branch main" ]] ||
    die 1 "$ENV_NAME may be used by more than main: $(tr '\n' ' ' <<<"$have")— remove the others in Settings → Environments → $ENV_NAME, then re-run"
  ok "$ENV_NAME: only main may use it"
}

secret_listed() {
  gh secret list --env "$ENV_NAME" --repo "$REPO" --json name --jq '.[].name' | grep -qxF "$SECRET"
}

# store_key: asks for the .pem path and sends the file to `gh secret set` on stdin. The key never
# passes through a shell variable, an argument or the terminal. Deletes the file once read back.
store_key() {
  local pem
  while :; do
    ask PEM_PATH "Path to the downloaded .pem file:" || die 2 "input ended"
    pem=${PEM_PATH/#\~/$HOME}
    if [[ ! -f $pem ]]; then warn "no file at $pem"; continue; fi
    if ! grep -q -e '-----BEGIN .*PRIVATE KEY-----' "$pem"; then
      warn "that file isn't a PEM private key"; continue
    fi
    break
  done
  confirm "Store it as $SECRET in $ENV_NAME?" || die 2 "you declined: nothing stored"
  gh secret set "$SECRET" --env "$ENV_NAME" --repo "$REPO" <"$pem" >/dev/null ||
    die 1 "gh secret set $SECRET --env $ENV_NAME failed; the .pem is kept"
  secret_listed || die 1 "$SECRET isn't listed in $ENV_NAME after setting it; the .pem is kept"
  WRITTEN_SECRET+=("$SECRET ($ENV_NAME)")
  ok "$SECRET is set in $ENV_NAME (listed by name)"
  if command -v shred >/dev/null 2>&1; then shred -u -- "$pem"; else rm -f -- "$pem"; fi
  ok "deleted $pem: GitHub keeps only the public half"
}

# check_installation: through the installations the admin's token sees. gh's own token may not
# be allowed to list them; then the admin reads the page and answers.
check_installation() {
  local inst id contents prs admin workflows selection repos
  if inst=$(gh api user/installations --paginate --jq '.installations[] | select(.app_slug == "sunny-factory")
      | "\(.id) \(.permissions.contents // "none") \(.permissions.pull_requests // "none") \(.permissions.administration // "none") \(.permissions.workflows // "none") \(.repository_selection)"' 2>/dev/null) &&
    [[ -n $inst ]]; then
    read -r id contents prs admin workflows selection <<<"$inst"
    [[ $contents == write && $prs == write ]] ||
      die 1 "the installation has contents: $contents, pull requests: $prs; both must be write"
    [[ $admin == none && $workflows == none ]] ||
      die 1 "the installation has administration: $admin, workflows: $workflows; both must be none"
    [[ $selection == selected ]] ||
      die 1 "the installation reaches all your repositories: choose Only select repositories"
    repos=$(gh api "user/installations/$id/repositories" --paginate --jq '.repositories[].full_name') ||
      die 1 "reading the installation's repositories failed"
    [[ $repos == "$REPO" ]] ||
      die 1 "the installation reaches $(tr '\n' ' ' <<<"$repos")— it must be $REPO only"
    ok "contents and pull requests write, no administration or workflows, on $REPO only"
  else
    note "gh's token can't list your App installations, so check the page yourself:"
    open_url "$APP_URL/permissions"
    step "Repository permissions: Contents and Pull requests are Read and write;"
    step "Administration and Workflows are No access."
    open_url "https://github.com/settings/installations"
    step "sunny-factory → Configure: Only select repositories → $REPO alone."
    confirm "Does it match?" || die 1 "fix the installation's permissions or repositories, then re-run"
    ok "checked by you"
  fi
}

run_wizard() {

TOTAL_STAGES=6

intro "#336: lanes open PRs as sunny-factory"

stage "Check gh"
command -v gh >/dev/null 2>&1 || die 2 "gh is not installed: https://cli.github.com"
gh auth status >/dev/null 2>&1 || die 2 "gh is signed out: run gh auth login, then re-run this"
say "gh is signed in. Every value below is set with gh, and no key is printed."
pause

stage "Environment $ENV_NAME"
say "The App's key lives only here. repository_dispatch runs main's workflow, so main alone"
say "may read it: Settings → Environments → $ENV_NAME → Deployment branches → Selected → main."
if [[ $(env_policy) == missing ]]; then
  confirm "Create $ENV_NAME with main as its only deployment branch?" ||
    die 2 "you declined: nothing created"
  gh api -X PUT "$E" --silent \
    -F 'deployment_branch_policy[protected_branches]=false' \
    -F 'deployment_branch_policy[custom_branch_policies]=true' ||
    die 1 "creating environment $ENV_NAME failed"
  gh api -X POST "$E/deployment-branch-policies" --silent -f name=main -f type=branch ||
    die 1 "adding main to $ENV_NAME's deployment branches failed"
fi
check_env
pause

replace_key=1
if secret_listed; then
  ok "$SECRET is already set in $ENV_NAME"
  confirm "Replace it with a new key?" || replace_key=0
fi

stage "sunny-factory: generate a private key"
if ((replace_key)); then
  open_url "$APP_URL"
  step "General → Private keys → Generate a private key."
  step "(On newer pages: Credentials → Key pairs → New key.) The browser downloads a .pem file."
  warn "Save it outside the repo, and never open it or paste it into a session."
else
  note "kept the key already stored; nothing to generate"
fi
pause

stage "Store the key in $ENV_NAME"
if ((replace_key)); then store_key; else note "kept the key already stored"; fi
pause

stage "The App's client ID"
current=$(gh variable get "$VAR" --env "$ENV_NAME" --repo "$REPO" 2>/dev/null || true)
open_url "$APP_URL"
step "On the App's page (General), copy the Client ID. It is not the App ID, and not a secret."
[[ -z $current ]] || note "now: $current (Enter keeps it)"
ask CLIENT_ID "Client ID:" || die 2 "input ended"
CLIENT_ID=${CLIENT_ID:-$current}
[[ -n $CLIENT_ID ]] || die 2 "no client ID"
[[ $CLIENT_ID =~ ^Iv[0-9A-Za-z._-]+$ ]] || warn "client IDs usually start with Iv; check it"
if [[ $CLIENT_ID != "$current" ]]; then
  gh variable set "$VAR" --env "$ENV_NAME" --repo "$REPO" --body "$CLIENT_ID" >/dev/null ||
    die 1 "gh variable set $VAR --env $ENV_NAME failed"
fi
[[ $(gh variable get "$VAR" --env "$ENV_NAME" --repo "$REPO") == "$CLIENT_ID" ]] ||
  die 1 "$VAR doesn't read back as $CLIENT_ID"
ok "$VAR is $CLIENT_ID in $ENV_NAME"
pause

stage "Check the App's installation"
check_installation
say "Next: merge #336's PR, then its throwaway test (the PR's \"For the admin\")."
pause

finish
}

run_wizard "$@"; exit
